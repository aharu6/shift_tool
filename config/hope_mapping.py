def normalize_hope_string(value):
    """希望セルの文字列から空白類（改行・半角/全角スペース等）を全て取り除く。

    希望表のセル内改行（例: '出\\n×'）や前後の空白でマッピング照合に
    失敗しないようにするための正規化。文字列以外はそのまま返す。
    """
    if isinstance(value, str):
        return re.sub(r"\s+", "", value)
    return value